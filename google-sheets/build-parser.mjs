// Generates Parser.gs (for Google Apps Script) from the Node app's offline parsers,
// so both versions understand the same phrases. Run: npm run build:sheets
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CATEGORIES } from '../src/ai/schema.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const strip = (file) => readFileSync(join(root, file), 'utf8')
  .replace(/^import .*$/gm, '')
  .replace(/^export (const|function) /gm, '$1 ');

const out = `// GENERATED by google-sheets/build-parser.mjs from src/ai/rulesParser.js and
// src/chat/rulesInterpreter.js. Do not edit by hand; edit those files and rebuild.

const CATEGORIES = ${JSON.stringify(CATEGORIES)};

${strip('src/ai/rulesParser.js')}
${strip('src/chat/rulesInterpreter.js')}`.replace(/\n{3,}/g, '\n\n');

writeFileSync(join(root, 'google-sheets', 'Parser.gs'), out);
console.log('Wrote google-sheets/Parser.gs');
